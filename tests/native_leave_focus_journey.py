"""Bounded issue105 Continue/return journey through the owned native input route."""


def run(command, wait, click, key, state, log):
    click('#new')
    wait("document.activeElement.id==='capture-title'")
    log.append({'setup': 'DOM seeds synthetic draft text/selection; activation and navigation below use the external OS sender'})
    command("const n=document.querySelector('#capture-title');n.value='保留原文与选择范围';n.dispatchEvent(new Event('input',{bubbles:true}));n.setSelectionRange(1,4)")

    def continue_editing():
        key('Escape')
        wait("!!document.querySelector('#task-leave-decision')")
        command("[...document.querySelectorAll('#task-leave-decision button')].find(n=>n.textContent==='继续编辑').id='native-continue'")
        click('#native-continue')
        wait("!document.querySelector('#task-leave-decision') && !(await import('./presentation.js')).taskLeavePending()")

    continue_editing()
    assert command("const n=document.querySelector('#capture-title');return n===document.activeElement&&n.selectionStart===1&&n.selectionEnd===4&&n.value==='保留原文与选择范围'")
    state('normal-continue-selection')
    key('Tab'); wait("document.activeElement.id==='capture-body'")
    key('Shift+Tab'); wait("document.activeElement.id==='capture-title'")
    state('normal-subsequent-tab-return')

    log.append({'setup': 'Deterministic scheduler holds only the real deferred leave-focus callback; releasing it is setup, not native input'})
    command("window.heldLeaveReturns=[];window.originalLeaveTimeout=window.setTimeout;window.setTimeout=(run,delay,...args)=>{if(run.toString().includes('origin.focus')&&run.toString().includes('task-leave-decision')){heldLeaveReturns.push(()=>run(...args));return 0;}return originalLeaveTimeout(run,delay,...args);}")
    continue_editing()
    assert command('return heldLeaveReturns.length===1')
    key('Tab'); wait("document.activeElement.id==='capture-body'")
    command('heldLeaveReturns.splice(0).forEach(run=>run())')
    assert command("return document.activeElement.id==='capture-body'")
    state('held-return-newer-native-tab')

    continue_editing()
    assert command('return heldLeaveReturns.length===1')
    click('#capture-title')
    command('heldLeaveReturns.splice(0).forEach(run=>run())')
    assert command("return document.activeElement.id==='capture-title'")
    state('held-return-newer-native-pointer')
    command('window.setTimeout=originalLeaveTimeout')

    click('#note-task-drawer .ui-drawer-header button')
    wait("!!document.querySelector('#task-leave-decision')")
    assert command("return document.querySelector('#note-task-drawer .ui-drawer-header button').disabled")
    command("[...document.querySelectorAll('#task-leave-decision button')].find(n=>n.textContent==='继续编辑').id='native-continue'")
    click('#native-continue')
    wait("!document.querySelector('#task-leave-decision') && !document.querySelector('#note-task-drawer .ui-drawer-header button').disabled")
    assert command("const n=document.activeElement;return document.querySelector('#note-task-drawer').contains(n)&&n.matches('input,textarea,button')")
    state('async-dismissal-continue-return')
    key('Tab')
    assert command("return document.querySelector('#note-task-drawer').contains(document.activeElement)")
    key('Shift+Tab')
    assert command("return document.querySelector('#note-task-drawer').contains(document.activeElement)")
    key('Escape')
    wait("!!document.querySelector('#task-leave-decision')")
    command("[...document.querySelectorAll('#task-leave-decision button')].find(n=>n.textContent==='放弃更改并离开').id='native-discard'")
    click('#native-discard')
    wait("!document.querySelector('dialog[open]') && !(await import('./presentation.js')).taskLeavePending()")
    assert command("return document.activeElement.id==='new' && !window.hasUnsavedChanges()")
    state('discard-restored-capture-opener')
    log.append({'issue105': 'Normal Continue/selection, native subsequent Tab, held stale return after newer native Tab/pointer, async dismissal fallback and discard/opener passed; no physical-input claim'})
